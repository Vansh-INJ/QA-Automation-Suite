# ============================================================
# HEALTH CLIENT
# ============================================================

@pytest.fixture(scope="session")
def health_client(
    base_url,
    token_managers,
):

    class HealthClient:

        def request(
            self,
            method: str,
            path: str,
            params: dict = None,
            auth_profile: str = None,
            json_body: dict = None,
        ):

            # -------------------------------------------------
            # BUILD URL
            # -------------------------------------------------

            url = f"{base_url}{path}"

            headers = {}

            # -------------------------------------------------
            # AUTHENTICATION
            # -------------------------------------------------

            if auth_profile:

                profile_cfg = AUTH_PROFILES[
                    auth_profile
                ]

                username, password = resolve_credentials(
                    profile_cfg
                )

                manager = token_managers[
                    auth_profile
                ]

                headers = manager.get_headers(
                    username,
                    password,
                )

            # -------------------------------------------------
            # REQUEST TIMER
            # -------------------------------------------------

            start = time.time()

            # -------------------------------------------------
            # API REQUEST
            # -------------------------------------------------

            resp = requests.request(
                method=method,
                url=url,
                params=params,
                headers=headers,
                json=json_body,
                timeout=20,
            )

            # -------------------------------------------------
            # RESPONSE TIME
            # -------------------------------------------------

            elapsed_ms = round(
                (time.time() - start) * 1000,
                1,
            )

            # -------------------------------------------------
            # RETURN EVERYTHING REQUIRED BY HEALTH TEST
            # -------------------------------------------------

            return (
                resp,
                elapsed_ms,
                url,
                headers,
            )

    return HealthClient()


