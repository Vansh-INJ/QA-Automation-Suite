    # ---------------------------------------------------------
    # TEST EXECUTION
    # ---------------------------------------------------------

    yield reporter

    # ---------------------------------------------------------
    # REPORT GENERATION
    # ---------------------------------------------------------

    try:
        report_path = reporter.write_excel()
        print(f"[health-suite] Excel report written: {report_path}")
    except Exception as e:
        print(f"[health-suite] Excel generation failed: {e}")
        report_path = None

    try:
        summary_path = reporter.write_summary_json()
        print(f"[health-suite] JSON summary written: {summary_path}")
    except Exception as e:
        print(f"[health-suite] JSON generation failed: {e}")
        summary_path = None

    # ---------------------------------------------------------
    # SUMMARY
    # ---------------------------------------------------------

    summary = reporter.summary

    print(
        f"[health-suite] "
        f"{summary['passed']}/"
        f"{summary['total']} passed "
        f"({summary['pass_rate']}%)"
    )

    if summary["critical_failed"]:

        print(
            "[health-suite] "
            f"CRITICAL FAILURES: "
            f"{summary['critical_failed']}"
        )

    if summary["sla_breaches"]:

        print(
            "[health-suite] "
            f"SLA BREACHES: "
            f"{summary['sla_breaches']}"
        )

    # ---------------------------------------------------------
    # RESEND HEALTH DASHBOARD EMAIL
    # ---------------------------------------------------------

    try:

        send_health_email(
            summary=summary,
            results=reporter.results,   
            environment=os.getenv(
                "HEALTH_ENVIRONMENT",
                "Development",
            ),
            report_path=report_path,
            summary_path=summary_path,
        )

        print(
            "[health-suite] "
            "Health dashboard email sent successfully."
        )

    except Exception as e:

        # VERY IMPORTANT:
        #
        # Email failure must NEVER make the health suite
        # appear broken when the actual API results exist.
        #
        print(
            "[health-suite] "
            f"Failed to send health dashboard email: {e}"
        )


